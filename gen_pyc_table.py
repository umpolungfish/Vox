#!/usr/bin/env python3
"""Generate src/pyc_table.rs from the running interpreter.

The opcode numbers, the jump sets and the inline-cache widths are properties of
one CPython version. Reading them off `dis` rather than retyping them is what
keeps the Rust lane from drifting the moment the interpreter moves.

    python3 gen_pyc_table.py
"""
import dis, opcode, importlib.util, sys

cache = getattr(opcode, "_inline_cache_entries", None)
def caches(op):
    if cache is None: return 0
    if isinstance(cache, dict): return cache.get(dis.opname[op], 0)
    return cache[op] if op < len(cache) else 0

rows = []
for op in range(256):
    name = dis.opname[op]
    if name.startswith('<'): continue
    rows.append('    (%3d, %-32s %d, %d, %d),' % (
        op, '"%s",' % name, int(op in dis.hasjrel), int(op in dis.hasjabs), caches(op)))

out = [
 '//! Generated by gen_pyc_table.py from the running interpreter.',
 '//! Do not edit: fix the generator and regenerate.',
 '',
 '/// The interpreter this table was read from.',
 'pub const PY_VERSION: &str = "%s";' % sys.version.split()[0],
 '/// .pyc magic for that interpreter, first four bytes of the header.',
 'pub const PYC_MAGIC: [u8; 4] = [%s];' % ', '.join(str(b) for b in importlib.util.MAGIC_NUMBER),
 '/// Opcodes below this take no argument byte pair beyond the implicit zero.',
 'pub const HAVE_ARGUMENT: u8 = %d;' % dis.HAVE_ARGUMENT,
 '',
 '/// (opcode, name, relative jump, absolute jump, inline cache entries)',
 'pub const OPS: [(u8, &str, u8, u8, u8); %d] = [' % len(rows),
 *rows,
 '];',
 '']
open('src/pyc_table.rs','w').write('\n'.join(out))
print("wrote src/pyc_table.rs: %d opcodes, python %s" % (len(rows), sys.version.split()[0]))
